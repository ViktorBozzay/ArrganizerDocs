<h1 id="Arrganizer-documentation">Arrganizer Documentation</h1>
<p>The <code class="object">Arrganizer</code> class is a zero-dependency TypeScript utility for organizing, transforming, and formatting data sets. It provides a fluent API to group, filter, modify, sort, aggregate, and format data, as well as full undo/redo history management.</p>
